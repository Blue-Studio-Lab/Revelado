export type StringKey = keyof typeof S;

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  const entry = S[key] as Entry | undefined;
  let s = entry ? entry[lang] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function fmtNumber(lang: Lang, n: number, digits = 1): string {
  return new Intl.NumberFormat(lang === 'es' ? 'es-ES' : 'en-GB', {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  }).format(n);
}

export function fmtDuration(lang: Lang, seconds: number | null | undefined): string {
  if (seconds == null || !isFinite(seconds) || seconds < 0) return '—';
  const s = Math.round(seconds);
  if (s < 60) return `${s} s`;
  const m = Math.floor(s / 60);
  if (m < 60) return `${m} min${s % 60 && m < 10 ? ` ${s % 60} s` : ''}`;
  const h = Math.floor(m / 60);
  return lang === 'es' ? `${h} h ${m % 60} min` : `${h} h ${m % 60} min`;
}
